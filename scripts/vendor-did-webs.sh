#!/usr/bin/env bash
# Rebuild vtn-service/web/did-webs.js: the did:webs resolver of @openvtc/vti-didcomm-js
# (CESR parsing, key event log verification, key-role designations), bundled into one
# browser ES module that the landing page imports when it meets a did:webs signer.
#
# Versions are pinned in vtn-service/web/vendor/package.json. To update, change them
# there and run this script; commit the regenerated did-webs.js with the pin change.
#
# The packages are installed and bundled in a temporary directory, never inside the
# repository, so nothing downloaded runs from the checkout.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
vendor="$root/vtn-service/web/vendor"
out="$root/vtn-service/web/did-webs.js"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cp "$vendor/package.json" "$work/"
(cd "$work" && npm install --ignore-scripts --no-audit --no-fund --silent)
# esbuild ships its binary in a platform package; installing with --ignore-scripts skips
# only its optional post-install check, not the binary.

version="$(node -p "require('$work/node_modules/@openvtc/vti-didcomm-js/package.json').version")"
esbuild_version="$(node -p "require('$work/node_modules/esbuild/package.json').version")"

cat > "$work/entry.js" <<'EOF'
export { resolve, parseDidWebs, DidWebsError } from "@openvtc/vti-didcomm-js/did-webs";
EOF

(cd "$work" && ./node_modules/.bin/esbuild entry.js \
  --bundle --format=esm --platform=browser --target=es2022 --minify \
  --legal-comments=none --outfile=bundle.js --log-level=warning)

{
  echo "// did:webs resolution for the VTN landing page: @openvtc/vti-didcomm-js@$version"
  echo "// (./did-webs: CESR, key event log and key-role designation checks), bundled with"
  echo "// esbuild@$esbuild_version. Generated by scripts/vendor-did-webs.sh from the pins in"
  echo "// vtn-service/web/vendor/package.json; do not edit by hand."
  echo "//"
  echo "// Bundled licences:"
  echo "//   @openvtc/vti-didcomm-js: Apache-2.0"
  echo "//   @noble/curves, @noble/hashes: MIT, Copyright (c) Paul Miller (https://paulmillr.com)"
  cat "$work/bundle.js"
} > "$out"

echo "wrote $out ($(wc -c < "$out" | tr -d ' ') bytes) from @openvtc/vti-didcomm-js@$version"
